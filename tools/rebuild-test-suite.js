function rebuildTestSuitePage() {
  const suiteDefinition = testCases.buildPipelineTestSuite();
  const htmlDocument = buildHtmlDocument(suiteDefinition);
  const dataScript = buildDataScript(suiteDefinition);
  const inboxFixtureDataScript = buildInboxFixtureDataScript();

  fs.writeFileSync(outputPath, htmlDocument, "utf8");
  fs.writeFileSync(dataOutputPath, dataScript, "utf8");
  fs.writeFileSync(inboxFixtureDataOutputPath, inboxFixtureDataScript, "utf8");
  console.log("Rebuilt generated test suite page: " + outputPath);
  console.log("Rebuilt generated test suite data: " + dataOutputPath);
  console.log("Rebuilt inbox browser fixture data: " + inboxFixtureDataOutputPath);
}

