function escapeHtml(value) {
  return String(value || "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function renderCaseUrl(caseDefinition) {
  const pageDefinition = caseDefinition.page || {};
  const escapedUrl = escapeHtml(pageDefinition.displayUrl || "");

  if (pageDefinition.displayKind === "anchor") {
    return (
      "                <a href=\"" +
      escapedUrl +
      "\">" +
      escapedUrl +
      "</a>"
    );
  }

  return "                <div class=\"suite-raw-url\">" + escapedUrl + "</div>";
}

function renderExpectedLines(caseDefinition) {
  return (caseDefinition.page && Array.isArray(caseDefinition.page.expectedLines) ? caseDefinition.page.expectedLines : [])
    .map(function mapExpectedLine(expectedLine) {
      return "                <p>" + expectedLine + "</p>";
    })
    .join("\n");
}

function renderSection(sectionDefinition) {
  const visibleCases = (sectionDefinition.cases || []).filter(function keepVisibleCase(caseDefinition) {
    return !!caseDefinition.page;
  });

  if (!visibleCases.length) {
    return "";
  }

  const introMarkup = (sectionDefinition.introLines || []).map(function mapIntroLine(introLine) {
    return "        <p>" + escapeHtml(introLine) + "</p>";
  }).join("\n");
  const tableRows = visibleCases.map(function mapCaseToRow(caseDefinition) {
    return [
      "            <tr>",
      "              <td class=\"suite-url-cell\">",
      "                <span class=\"suite-case-label\">" + escapeHtml(caseDefinition.page.caseLabel || caseDefinition.title) + "</span>",
      renderCaseUrl(caseDefinition),
      "              </td>",
      "              <td class=\"suite-expected-cell\">",
      renderExpectedLines(caseDefinition),
      "              </td>",
      "            </tr>"
    ].join("\n");
  }).join("\n");

  return [
    "      <section class=\"suite-section\">",
    "        <h2>" + escapeHtml(sectionDefinition.title) + "</h2>",
    introMarkup,
    "        <div class=\"suite-table-wrap\">",
    "        <table class=\"suite-table\" aria-label=\"" + escapeHtml(sectionDefinition.title) + "\">",
    "          <colgroup>",
    "            <col class=\"suite-table__input-column\">",
    "            <col class=\"suite-table__expected-column\">",
    "          </colgroup>",
    "          <thead>",
    "            <tr>",
    "              <th scope=\"col\">Input</th>",
    "              <th scope=\"col\">Expected Output</th>",
    "            </tr>",
    "          </thead>",
    "          <tbody>",
    tableRows,
    "          </tbody>",
    "        </table>",
    "        </div>",
    "      </section>"
  ].join("\n");
}

function buildDataScript(suiteDefinition) {
  return [
    "// Generated by tools/rebuild-test-suite.js",
    "(function attachUrlForensicsTestSuiteData(globalScope) {",
    "  \"use strict\";",
    "",
    "  var suiteDefinition = " + JSON.stringify(suiteDefinition, null, 2) + ";",
    "",
    "  if (globalScope) {",
    "    globalScope.urlForensicsTestSuiteData = suiteDefinition;",
    "  }",
    "}(typeof globalThis !== \"undefined\" ? globalThis : window));",
    ""
  ].join("\n");
}

function buildInboxFixtureDataScript() {
  const browserFixtureDefinitions = fixtureDefinitions.map(function mapFixtureDefinition(fixtureDefinition) {
    return {
      providerId: fixtureDefinition.providerId,
      title: fixtureDefinition.title,
      fixtureUrl: fixtureDefinition.fixtureUrl,
      expectedSelectors: fixtureDefinition.expectedSelectors.slice(),
      expectedPrimaryTagName: fixtureDefinition.expectedPrimaryTagName,
      expectedDetectionMode: fixtureDefinition.expectedDetectionMode,
      expectedRawTextIncludes: fixtureDefinition.expectedRawTextIncludes.slice(),
      expectedFinalUrls: fixtureDefinition.expectedFinalUrls.slice(),
      sourceHtml: fs.readFileSync(fixtureDefinition.fixturePath, "utf8"),
      nestedFrames: (fixtureDefinition.nestedFrames || []).map(function mapNestedFrameDefinition(nestedFrameDefinition) {
        return {
          selector: nestedFrameDefinition.selector,
          sourceHtml: fs.readFileSync(nestedFrameDefinition.fixturePath, "utf8")
        };
      })
    };
  });

  return [
    "// Generated by tools/rebuild-test-suite.js",
    "(function attachUrlForensicsInboxFixtureData(globalScope) {",
    "  \"use strict\";",
    "",
    "  var fixtureData = " + JSON.stringify(browserFixtureDefinitions, null, 2) + ";",
    "",
    "  if (globalScope) {",
    "    globalScope.urlForensicsInboxFixtureData = fixtureData;",
    "  }",
    "}(typeof globalThis !== \"undefined\" ? globalThis : window));",
    ""
  ].join("\n");
}

