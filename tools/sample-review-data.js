"use strict";

const fs = require("node:fs");
const path = require("node:path");

const detectorParity = require("./pipeline-detector-parity.js");

const extensionDirectoryPath = path.resolve(__dirname, "..", "lab", "firefox-extension");
const sampleReviewDataOutputPath = path.join(extensionDirectoryPath, "sample-review-data.js");
const generatedBy = "tools/rebuild-sample-review-data.js";

function formatSampleTitle(sampleId) {
  return String(sampleId || "")
    .split("-")
    .filter(Boolean)
    .map(function mapSegment(segment) {
      return segment.charAt(0).toUpperCase() + segment.slice(1);
    })
    .join(" ");
}

function readExtensionVersion() {
  const manifestPath = path.join(extensionDirectoryPath, "manifest.json");
  const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
  return String(manifest && manifest.version ? manifest.version : "0.0.0");
}

function buildSampleReviewData(options) {
  const optionBag = options && typeof options === "object" ? options : {};
  const generatedAt = typeof optionBag.generatedAt === "string" && optionBag.generatedAt.trim()
    ? optionBag.generatedAt.trim()
    : new Date().toISOString();

  return {
    schemaVersion: 1,
    generatedAt: generatedAt,
    generatedBy: generatedBy,
    extensionVersion: readExtensionVersion(),
    expectedDetectorIds: detectorParity.expectedDetectorIds.slice(),
    textSamples: detectorParity.paritySamples.map(function mapParitySample(paritySample) {
      return {
        id: paritySample.id,
        title: formatSampleTitle(paritySample.id),
        input: paritySample.input,
        options: Object.assign({}, paritySample.options || {})
      };
    })
  };
}

function buildSampleReviewDataScript(sampleReviewData) {
  return [
    "// Generated by " + generatedBy,
    "(function attachUrlForensicsSampleReviewData(globalScope) {",
    "  \"use strict\";",
    "",
    "  var sampleReviewData = " + JSON.stringify(sampleReviewData, null, 2) + ";",
    "",
    "  if (globalScope) {",
    "    globalScope.urlForensicsSampleReviewData = sampleReviewData;",
    "  }",
    "}(typeof globalThis !== \"undefined\" ? globalThis : window));",
    ""
  ].join("\n");
}

module.exports = Object.freeze({
  buildSampleReviewData: buildSampleReviewData,
  buildSampleReviewDataScript: buildSampleReviewDataScript,
  sampleReviewDataOutputPath: sampleReviewDataOutputPath,
  generatedBy: generatedBy
});
